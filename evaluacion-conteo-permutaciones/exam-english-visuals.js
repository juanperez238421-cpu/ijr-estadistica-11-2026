(() => {
  'use strict';

  const topicNames = {
    FCP: 'Fundamental Counting Principle',
    P_SIMPLE: 'Simple / Partial Permutation',
    P_DIST: 'Permutations with Repeated Elements',
    P_CIRC: 'Circular Permutation'
  };

  const exactTextMap = new Map([
    ['Etapa A', 'Stage A'],
    ['Etapa B', 'Stage B'],
    ['Etapa C', 'Stage C'],
    ['Pregunta', 'Question'],
    ['Cargando pregunta…', 'Loading question…']
  ]);

  function translateTextNode(node) {
    if (!node || node.nodeType !== Node.TEXT_NODE) return;
    const raw = node.nodeValue || '';
    const trimmed = raw.trim();
    if (!trimmed) return;

    if (exactTextMap.has(trimmed)) {
      node.nodeValue = raw.replace(trimmed, exactTextMap.get(trimmed));
      return;
    }

    if (/^\d+\s+elementos$/i.test(trimmed)) {
      node.nodeValue = raw.replace(trimmed, trimmed.replace(/elementos/i, 'items'));
      return;
    }

    if (/^Etapa\s+/i.test(trimmed)) {
      node.nodeValue = raw.replace(trimmed, trimmed.replace(/^Etapa/i, 'Stage'));
    }
  }

  function translateElementText(root) {
    if (!root) return;
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    nodes.forEach(translateTextNode);
  }

  function enlargeDiagram() {
    const diagram = document.getElementById('diagram');
    if (!diagram) return;
    const wrap = diagram.firstElementChild;
    if (!wrap) return;

    wrap.style.setProperty('min-height', '165px', 'important');
    wrap.style.setProperty('padding', '26px 28px', 'important');
    wrap.style.setProperty('gap', '24px', 'important');
    wrap.style.setProperty('border-radius', '14px', 'important');
    wrap.style.setProperty('width', '100%', 'important');
    wrap.style.setProperty('box-sizing', 'border-box', 'important');

    // Token boxes generated by app.js have a visible border and white background.
    wrap.querySelectorAll('div').forEach(el => {
      const style = el.style;
      const isCircle = style.position === 'relative' && style.borderRadius === '50%';
      const isToken = !isCircle && style.border && style.background && style.background.includes('white');

      if (isToken) {
        style.setProperty('font-size', '1.22rem', 'important');
        style.setProperty('min-width', '74px', 'important');
        style.setProperty('padding', '13px 18px', 'important');
        style.setProperty('border-radius', '9px', 'important');
      }

      if (isCircle) {
        style.setProperty('transform', 'scale(1.32)', 'important');
        style.setProperty('transform-origin', 'center', 'important');
        style.setProperty('margin', '30px 42px', 'important');
      }
    });

    // Stage captions and arrows.
    wrap.querySelectorAll('div').forEach(el => {
      if (!el.style.border && el.style.marginTop) {
        el.style.setProperty('font-size', '1.02rem', 'important');
        el.style.setProperty('font-weight', '650', 'important');
      }
    });
    wrap.querySelectorAll(':scope > span').forEach(el => {
      el.style.setProperty('font-size', '1.9rem', 'important');
      el.style.setProperty('font-weight', '700', 'important');
    });

    translateElementText(wrap);
  }

  function localizeExamChrome() {
    const topic = document.getElementById('topicLabel');
    if (topic && topicNames[topic.textContent.trim()]) {
      topic.textContent = topicNames[topic.textContent.trim()];
    }

    const progress = document.getElementById('progressText');
    if (progress) progress.textContent = progress.textContent.replace(/^Pregunta\s+/i, 'Question ');

    const submit = document.getElementById('submitAnswer');
    if (submit) submit.textContent = 'Confirm answer';

    const prompt = document.getElementById('questionPrompt');
    if (prompt && prompt.textContent.trim() === 'Cargando pregunta…') prompt.textContent = 'Loading question…';
  }

  function apply() {
    localizeExamChrome();
    enlargeDiagram();
  }

  const targets = ['diagram', 'topicLabel', 'progressText', 'questionPrompt'];
  targets.forEach(id => {
    const node = document.getElementById(id);
    if (!node) return;
    new MutationObserver(() => requestAnimationFrame(apply)).observe(node, {
      childList: true,
      subtree: true,
      characterData: true
    });
  });

  window.addEventListener('load', apply, { once: true });
  apply();
})();
